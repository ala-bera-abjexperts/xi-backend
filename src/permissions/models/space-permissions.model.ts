/**
 * The space-level authorisation facts for one user in one space, resolved once so a
 * caller can decide several permission keys without re-querying.
 *
 * This is deliberately the *guard's* view of the world: the membership row is read
 * only for explicit `true` grants, and anything else falls back to the base role.
 * A stored `false` therefore never denies — it means "not explicitly granted here",
 * not "explicitly revoked". `space_permissions` / `space_module_permissions`
 * overrides are NOT applied; those are consumed by
 * {@link PermissionsService.getUserSpacePermissions} for display purposes.
 */
export interface ISpaceBaseGrant {
  /** Org admins and owners bypass space-level checks entirely. */
  isAdmin: boolean;
  /** False when the user has no active `space_members` row (and is not an admin). */
  isMember: boolean;
  /** The raw `space_role` from the membership row — never normalised. */
  spaceRole: string | null;
  /** Explicit grants from the membership row; only `true` values are meaningful. */
  explicit: Record<string, boolean>;
  /** Base permissions for {@link ISpaceBaseGrant.spaceRole}; empty for unknown roles. */
  basePermissions: Record<string, boolean>;
}

/**
 * Decide a single permission against a resolved grant.
 *
 * Order: admin bypass → membership requirement → explicit `true` on the membership
 * row → base-role default. Accepts keys with or without the `can_` prefix.
 *
 * @param {ISpaceBaseGrant} grant - Resolved facts from `resolveSpaceBaseGrant`
 * @param {string} permission - Permission key, e.g. `view_file_explorer` or `can_edit_tasks`
 * @returns {boolean} `true` when the user holds the permission in that space
 */
export function spaceGrantAllows(
  grant: ISpaceBaseGrant,
  permission: string,
): boolean {
  if (grant.isAdmin) return true;
  if (!grant.isMember) return false;

  const flatKey = permission.startsWith('can_')
    ? permission.slice(4)
    : permission;

  if (['view_sla', 'manage_sla', 'publish_customer_replies'].includes(flatKey) && typeof grant.explicit[flatKey] === 'boolean') return grant.explicit[flatKey];

  if (grant.explicit[flatKey] === true) return true;

  return grant.basePermissions[flatKey] === true;
}

