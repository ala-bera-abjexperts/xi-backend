/**
 * Normalizes space permissions by ensuring that action permissions automatically
 * grant their implied view permissions. For example, if `edit_tasks` is `true`,
 * `view_tasks` will be set to `true` as well.
 *
 * @param {Record<string, boolean>} perms - The raw permissions to normalize
 * @returns {Record<string, boolean>} The normalized permissions with implied views set to `true`
 */
export function normalizeSpacePermissions(
  perms: Record<string, boolean>,
): Record<string, boolean> {
  const result = { ...perms };

  for (const rule of NORMALIZATION_RULES) {
    if (result[rule.action] === true) {
      result[rule.impliesView] = true;
    }
  }

  return result;
}

