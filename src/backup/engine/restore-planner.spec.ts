/**
 * @fileoverview Tests for the restore preflight.
 * @module src/backup/engine/restore-planner.spec
 *
 * Every assertion here is about a REFUSAL. A restore cannot be rolled back, so
 * the only place safety exists is before the first row is written — a planner
 * that lets a bad restore start has already failed, whatever it does afterwards.
 */

import {
  availableDependencyTables,
  GENERATED_COLUMNS,
  IDENTITY_COLUMN_TABLES,
  generatedColumnsFor,
  isRestorableFormat,
  orderForInsert,
  planRestore,
  refuseTable,
  resolveRestoreSet,
  requiredComponents,
  type PlannedTable,
} from './restore-planner';
import {
  COMPONENT_REGISTRY,
  tableEntry,
  tableRestorable,
} from '../registry/component-registry';

const ORG = 'org-1';

function input(overrides: Partial<Parameters<typeof planRestore>[0]> = {}) {
  return {
    selection: ['tasks'],
    format: 'ndjson' as const,
    archiveOrganizationId: ORG,
    sessionOrganizationId: ORG,
    ...overrides,
  };
}

describe('format gate', () => {
  it('accepts only the formats the app can actually read back', () => {
    expect(isRestorableFormat('ndjson')).toBe(true);
    expect(isRestorableFormat('json')).toBe(true);

    // SQL is the DEFAULT backup format, so most archives are SQL. It reads back through
    // sql.reader.ts, which parses the dump rather than executing it — there is still no Postgres
    // driver anywhere in this backend.
    expect(isRestorableFormat('sql')).toBe(true);

    // These stay refused, and not for want of a parser. A delimited file cannot tell an empty
    // string from a NULL, and the formula guard rewrites any value starting with = + - @ on the
    // way out — so a negative number is already altered in the file. xml keeps null and empty
    // apart but loses every type.
    expect(isRestorableFormat('csv')).toBe(false);
    expect(isRestorableFormat('tsv')).toBe(false);
    expect(isRestorableFormat('xlsx')).toBe(false);
    expect(isRestorableFormat('xml')).toBe(false);
  });

  it('plans a SQL archive rather than refusing it', () => {
    const plan = planRestore(input({ format: 'sql' }));

    // The refusal an operator used to meet first. Every archive this product had written was SQL,
    // so "restore" was unreachable in practice until the reader existed.
    expect(plan.canProceed).toBe(true);
    expect(plan.refusals.map((refusal) => refusal.code)).not.toContain(
      'format_not_restorable',
    );
  });

  it('refuses a CSV archive fatally, before planning anything', () => {
    const plan = planRestore(input({ format: 'csv' }));

    // Not a parser gap. The file itself no longer holds what the database had.
    expect(plan.canProceed).toBe(false);
    expect(plan.tables).toEqual([]);
    expect(plan.refusals[0].code).toBe('format_not_restorable');
  });
});

describe('tenant boundary', () => {
  it('refuses an archive from another organization before reading it', () => {
    const plan = planRestore(input({ archiveOrganizationId: 'someone-else' }));

    expect(plan.canProceed).toBe(false);
    expect(plan.tables).toEqual([]);
    expect(plan.refusals.map((r) => r.code)).toContain('foreign_organization');
  });

  it('does not even compute a plan for a foreign archive', () => {
    // Nothing about the selection should be reported back for an archive the
    // caller is not entitled to — not even which of its tables would be valid.
    const plan = planRestore(
      input({ archiveOrganizationId: 'someone-else', selection: ['tasks'] }),
    );

    expect(plan.missingParentComponents).toEqual([]);
  });
});

describe('per-table refusals', () => {
  it('no longer refuses a table whose identity column accepts archived values', () => {
    const plan = planRestore(input({ selection: ['support_requests'] }));

    // `ticket_number` was GENERATED ALWAYS, so PostgREST could not write the archived numbers and
    // inserting without the column silently renumbered every ticket — which is why the whole table
    // was refused. `20260813140000_restore_identity_columns.sql` moves it to GENERATED BY DEFAULT,
    // so the numbers write back and there is nothing left to refuse. This is the behaviour that
    // migration exists to produce.
    expect(
      plan.refusals.find((r) => r.code === 'identity_column'),
    ).toBeUndefined();
    expect(plan.tables.some((t) => t.table === 'support_requests')).toBe(true);
  });

  it('keeps the identity-column refusal wired with no members', () => {
    // Emptied rather than deleted, exactly as SEQUENCE_PRIMARY_KEY_TABLES is: a column added as
    // GENERATED ALWAYS later is refused by a guard that is already in place. Anchored on the
    // constant rather than on a table, because there is deliberately no table left to name.
    expect([...IDENTITY_COLUMN_TABLES]).toEqual([]);
  });

  it('refuses identity-tier tables unless they were separately approved', () => {
    const plan = planRestore(input({ selection: ['organization_members'] }));

    const refusal = plan.refusals.find((r) => r.code === 'identity_tier');

    expect(refusal).toBeDefined();
    expect(refusal?.detail).toContain('who has access');
  });

  it('refuses a table that is not in the registry rather than guessing', () => {
    const plan = planRestore(input({ selection: ['not_a_real_table'] }));

    expect(plan.refusals.map((r) => r.code)).toContain('not_in_registry');
    expect(plan.canProceed).toBe(false);
  });

  it('keeps the good tables when one is refused', () => {
    const plan = planRestore(
      input({ selection: ['tasks', 'not_a_real_table'] }),
    );

    // Reporting nine of ten with the tenth named beats refusing all ten.
    expect(plan.tables.some((t) => t.table === 'tasks')).toBe(true);
    expect(plan.refusals).toHaveLength(1);
    expect(plan.canProceed).toBe(true);
  });
});

describe('dependencies', () => {
  it('restores ONLY what was selected', () => {
    const plan = planRestore(input({ selection: ['tasks'] }));

    // The whole point of the change. Selecting Tasks used to restore 20 tables across five
    // components — spaces, statuses and process configuration nobody asked to have rewritten.
    expect(plan.tables.map((t) => t.table)).toEqual(['tasks']);
  });

  it('names the parents it did NOT bring along', () => {
    const plan = planRestore(input({ selection: ['tasks'] }));

    // Reported so the skips that follow are expected rather than mysterious.
    expect(plan.missingParentComponents.length).toBeGreaterThan(0);
    expect(plan.missingParentComponents).toContain('spaces');
  });

  it('never marks a planned table as added by a dependency', () => {
    const plan = planRestore(input({ selection: ['tasks'] }));

    expect(plan.tables.every((t) => !t.addedAsDependency)).toBe(true);
  });

  it('adds required relation parents found in the archive when requested', () => {
    const plan = planRestore(
      input({
        selection: ['form_builder_approval_steps'],
        availableTables: [
          'form_builder_approval_steps',
          'form_builder_approvals',
          'form_builder_submissions',
          'form_builder',
        ],
        includeAvailableDependencies: true,
      }),
    );

    expect(plan.tables.map((t) => t.table)).toEqual([
      'form_builder',
      'form_builder_submissions',
      'form_builder_approvals',
      'form_builder_approval_steps',
    ]);
    expect(
      plan.tables
        .filter((t) => t.addedAsDependency)
        .map((t) => t.table)
        .sort(),
    ).toEqual([
      'form_builder',
      'form_builder_approvals',
      'form_builder_submissions',
    ]);
    expect(
      plan.tables
        .filter((t) => t.addedAsDependency)
        .every((t) => t.restoreDependencyRows),
    ).toBe(true);
  });

  it('does not add optional relation parents just because the archive has them', () => {
    const plan = planRestore(
      input({
        selection: ['form_builder_submissions'],
        availableTables: ['form_builder_submissions', 'form_builder', 'tasks'],
        includeAvailableDependencies: true,
      }),
    );

    expect(plan.tables.map((t) => t.table)).toEqual([
      'form_builder',
      'form_builder_submissions',
    ]);
  });

  it('keeps the existing order parent expansion', () => {
    const plan = planRestore(
      input({
        selection: ['form_builder_orders'],
        availableTables: [
          'form_builder_orders',
          'form_builder',
          'form_builder_submissions',
        ],
        includeAvailableDependencies: true,
      }),
    );

    expect(plan.tables.map((t) => t.table)).toEqual([
      'form_builder',
      'form_builder_submissions',
      'form_builder_orders',
    ]);
  });

  it('adds the form delivery parent tables that hold the related ids', () => {
    const plan = planRestore(
      input({
        selection: ['form_builder_webhook_deliveries'],
        availableTables: [
          'form_builder_webhook_deliveries',
          'form_builder_webhooks',
          'form_builder_submissions',
          'form_builder',
        ],
        includeAvailableDependencies: true,
      }),
    );

    expect(
      plan.tables
        .filter((t) => t.addedAsDependency)
        .map((t) => t.table)
        .sort(),
    ).toEqual([
      'form_builder',
      'form_builder_submissions',
      'form_builder_webhooks',
    ]);
    expect(plan.tables.at(-1)?.table).toBe('form_builder_webhook_deliveries');
  });

  it('keeps polymorphic attachment parent expansion tied to logical dependencies', () => {
    const plan = planRestore(
      input({
        selection: ['file_attachments'],
        availableTables: [
          'file_attachments',
          'tasks',
          'business_processes',
          'wiki_pages',
          'asset_items',
          'gdpr_records',
          'space_gdpr_records',
          'support_requests',
        ],
        includeAvailableDependencies: true,
      }),
    );

    expect(
      plan.tables
        .filter((t) => t.addedAsDependency)
        .map((t) => t.table)
        .sort(),
    ).toEqual([
      'asset_items',
      'business_processes',
      'gdpr_records',
      'space_gdpr_records',
      'support_requests',
      'tasks',
      'wiki_pages',
    ]);
  });

  it('does not report a parent the selection already covers', () => {
    const plan = planRestore(input({ selection: ['tasks', 'spaces'] }));

    expect(plan.missingParentComponents).not.toContain('spaces');
  });

  it('terminates on a component graph that references itself', () => {
    // The FK graph has real cycles; a naive walk over `requires` would hang.
    expect(() => requiredComponents(['tasks'])).not.toThrow();
    expect(() => requiredComponents(['wiki'])).not.toThrow();
  });
});

describe('insert order', () => {
  it('puts parents strictly before children', () => {
    const plan = planRestore(input({ selection: ['tasks'] }));
    const levels = plan.tables.map((t) => t.insertLevel);

    expect(levels).toEqual([...levels].sort((a, b) => a - b));
  });

  it('is deterministic within a level', () => {
    const rows: PlannedTable[] = [
      {
        table: 'b',
        component: 'x',
        tier: 'content',
        insertLevel: 2,
        generatedColumns: [],
        addedAsDependency: false,
      },
      {
        table: 'a',
        component: 'x',
        tier: 'content',
        insertLevel: 2,
        generatedColumns: [],
        addedAsDependency: false,
      },
      {
        table: 'c',
        component: 'x',
        tier: 'content',
        insertLevel: 1,
        generatedColumns: [],
        addedAsDependency: false,
      },
    ];

    expect(orderForInsert(rows).map((r) => r.table)).toEqual(['c', 'a', 'b']);
  });

  it('writes tickets before the test records that require them', () => {
    const records = [
      'test_cases',
      'test_sets',
      'test_plans',
      'test_executions',
    ];
    const planned = (table: string): PlannedTable => ({
      table,
      component: 'x',
      tier: 'content',
      insertLevel: tableEntry(table)?.insertLevel ?? 0,
      generatedColumns: [],
      addedAsDependency: false,
    });
    const order = orderForInsert([...records, 'tasks'].map(planned)).map(
      (r) => r.table,
    );

    for (const table of records) {
      expect(order.indexOf('tasks')).toBeLessThan(order.indexOf(table));
    }
  });

  it('pulls tickets in when only a test record was picked', () => {
    expect(
      availableDependencyTables(
        ['test_cases'],
        new Set(['test_cases', 'tasks']),
        false,
      ),
    ).toContain('tasks');
    expect(requiredComponents(['test_cases'])).toContain('tasks');
  });

  it('writes settings, then preconditions, then cases, then attempts', () => {
    const tables = [
      'test_run_attempts',
      'test_cases',
      'test_preconditions',
      'test_management_space_settings',
      'test_runs',
      'test_executions',
      'tasks',
    ];
    const planned = (table: string): PlannedTable => ({
      table,
      component: 'x',
      tier: 'content',
      insertLevel: tableEntry(table)?.insertLevel ?? 0,
      generatedColumns: [],
      addedAsDependency: false,
    });
    const order = orderForInsert(tables.map(planned)).map((r) => r.table);
    const at = (table: string) => order.indexOf(table);

    expect(at('test_management_space_settings')).toBeLessThan(
      at('test_preconditions'),
    );
    expect(at('test_preconditions')).toBeLessThan(at('test_cases'));
    expect(at('test_cases')).toBeLessThan(at('test_run_attempts'));
  });

  it('brings archived preconditions along with test cases, and test records along with their evidence', () => {
    expect(
      availableDependencyTables(
        ['test_cases'],
        new Set(['test_cases', 'test_preconditions', 'tasks']),
        false,
      ),
    ).toContain('test_preconditions');
    expect(
      availableDependencyTables(
        ['file_attachments'],
        new Set(['file_attachments', 'test_cases', 'tasks']),
        false,
      ),
    ).toContain('test_cases');
  });
});

describe('generated columns', () => {
  it('names the columns Postgres computes, so they are never sent', () => {
    // Sending a GENERATED ALWAYS AS STORED column is an error, not an override —
    // Postgres rejects the whole row.
    expect(generatedColumnsFor('partner_leads')).toContain(
      'customer_company_normalized',
    );
    expect(generatedColumnsFor('tasks')).toEqual([]);
  });

  it('carries them onto the plan so the writer cannot forget', () => {
    const plan = planRestore(input({ selection: ['partner_leads'] }));
    const row = plan.tables.find((t) => t.table === 'partner_leads');

    expect(row?.generatedColumns).toEqual(GENERATED_COLUMNS.partner_leads);
  });
});

describe('empty outcome', () => {
  it('treats a plan with no tables as a refusal, not a success', () => {
    const plan = planRestore(input({ selection: [] }));

    // "Restored 0 tables" reported as success is how an empty restore passes
    // for a real one.
    expect(plan.canProceed).toBe(false);
  });
});

describe('resolveRestoreSet — what the destination counts change', () => {
  const plannedFor = (
    table: string,
    addedAsDependency: boolean,
    insertLevel = 5,
  ): PlannedTable => ({
    table,
    component: 'tasks',
    tier: 'content',
    insertLevel,
    generatedColumns: [],
    addedAsDependency,
  });

  const planOf = (
    tables: PlannedTable[],
  ): Parameters<typeof resolveRestoreSet>[0] => ({
    tables,
    refusals: [],
    missingParentComponents: [],
    canProceed: true,
  });

  it('restores a chosen table whose destination is empty', () => {
    const resolved = resolveRestoreSet(
      planOf([plannedFor('task_comments', false)]),
      [{ table: 'task_comments', liveRowCount: 0, empty: true }],
    );

    expect(resolved.canProceed).toBe(true);
    expect(resolved.tables.map((t) => t.table)).toEqual(['task_comments']);
    expect(resolved.tables[0].mergeIntoExisting).toBe(false);
  });

  it('treats a non-empty DEPENDENCY as satisfied, not as a refusal', () => {
    // The exact shape that made every restore on the live database impossible: the one empty table
    // drags in three non-empty parents. Those parents are what the child needs to point at.
    const resolved = resolveRestoreSet(
      planOf([
        plannedFor('task_comments', false, 6),
        plannedFor('tasks', true, 5),
        plannedFor('spaces', true, 2),
        plannedFor('relation_types', true, 1),
      ]),
      [
        { table: 'task_comments', liveRowCount: 0, empty: true },
        { table: 'tasks', liveRowCount: 126, empty: false },
        { table: 'spaces', liveRowCount: 3, empty: false },
        { table: 'relation_types', liveRowCount: 18, empty: false },
      ],
    );

    expect(resolved.canProceed).toBe(true);
    expect(resolved.tables.map((t) => t.table)).toEqual(['task_comments']);
    expect(resolved.satisfied.map((s) => s.table).sort()).toEqual([
      'relation_types',
      'spaces',
      'tasks',
    ]);
  });

  it('reports the live count of a satisfied parent rather than hiding it', () => {
    const resolved = resolveRestoreSet(planOf([plannedFor('tasks', true)]), [
      { table: 'tasks', liveRowCount: 126, empty: false },
    ]);

    expect(resolved.satisfied[0].liveRowCount).toBe(126);
    expect(resolved.warnings[0].code).toBe('satisfied_by_existing');
  });

  it('still restores archive-derived dependency rows when the destination table is non-empty', () => {
    const resolved = resolveRestoreSet(
      planOf([
        {
          ...plannedFor('form_builder', true),
          restoreDependencyRows: true,
        },
      ]),
      [{ table: 'form_builder', liveRowCount: 3, empty: false }],
    );

    expect(resolved.tables.map((t) => t.table)).toEqual(['form_builder']);
    expect(resolved.satisfied).toEqual([]);
    expect(resolved.tables[0].mergeIntoExisting).toBe(true);
    expect(resolved.warnings[0].code).toBe('destination_not_empty');
  });

  it('merges into a non-empty table the operator CHOSE, and warns', () => {
    const resolved = resolveRestoreSet(planOf([plannedFor('tasks', false)]), [
      { table: 'tasks', liveRowCount: 126, empty: false },
    ]);

    // Safe because the writer is INSERT-only: present rows are counted as skipped, never rewritten.
    expect(resolved.tables[0].mergeIntoExisting).toBe(true);
    expect(resolved.warnings[0].code).toBe('destination_not_empty');
    expect(resolved.warnings[0].detail).toContain('126');
  });

  it('BLOCKS on a count that failed — an unknown count is still not zero', () => {
    const resolved = resolveRestoreSet(planOf([plannedFor('tasks', false)]), [
      {
        table: 'tasks',
        liveRowCount: 0,
        empty: false,
        error: 'permission denied',
      },
    ]);

    expect(resolved.canProceed).toBe(false);
    expect(resolved.blocked[0].detail).toContain('permission denied');
    expect(resolved.tables).toEqual([]);
  });

  it('blocks a table nobody counted rather than assuming it is empty', () => {
    const resolved = resolveRestoreSet(
      planOf([plannedFor('tasks', false)]),
      [],
    );

    expect(resolved.canProceed).toBe(false);
    expect(resolved.blocked[0].table).toBe('tasks');
  });

  it('keeps parents strictly before children in what it restores', () => {
    const resolved = resolveRestoreSet(
      planOf([
        plannedFor('task_comments', false, 6),
        plannedFor('tasks', false, 5),
        plannedFor('spaces', false, 2),
      ]),
      [
        { table: 'task_comments', liveRowCount: 0, empty: true },
        { table: 'tasks', liveRowCount: 0, empty: true },
        { table: 'spaces', liveRowCount: 0, empty: true },
      ],
    );

    expect(resolved.tables.map((t) => t.table)).toEqual([
      'spaces',
      'tasks',
      'task_comments',
    ]);
  });

  it('refuses when everything turned out to be satisfied already', () => {
    // Nothing left to write. Reporting that as success is how an empty restore passes for a real one.
    const resolved = resolveRestoreSet(planOf([plannedFor('tasks', true)]), [
      { table: 'tasks', liveRowCount: 126, empty: false },
    ]);

    expect(resolved.canProceed).toBe(false);
    expect(resolved.tables).toEqual([]);
  });
});

/**
 * The test `component-registry.ts` has always said existed.
 *
 * `tableRestorable()` restates `refuseTable()`'s rules so the picker can grey out what the engine
 * will reject, and its docblock claims "the pairing is asserted in the registry spec instead, so the
 * two cannot drift silently". No such assertion was ever written — nothing in the tree referenced
 * either symbol — so the duplication has been unguarded the whole time. It lives here rather than in
 * the registry spec because the registry must not import the engine.
 */
describe('tableRestorable mirrors refuseTable', () => {
  it('agrees with the planner for every table in the registry', () => {
    const disagreed = COMPONENT_REGISTRY.filter(
      (entry) =>
        tableRestorable(entry) !== (refuseTable(entry, false) === null),
    ).map((entry) => entry.table);

    expect(disagreed).toEqual([]);
  });

  /**
   * The identity tier is the one place they are MEANT to differ, and only in one direction. The
   * registry projection has no session to ask about approval, so it reports the tier unrestorable;
   * the planner accepts it once a run carries identity approval.
   */
  it('differs on the identity tier only once approval is granted', () => {
    const identity = COMPONENT_REGISTRY.filter(
      (entry) => entry.tier === 'identity',
    );

    expect(identity.length).toBeGreaterThan(0);

    for (const entry of identity) {
      expect(tableRestorable(entry)).toBe(false);
      expect(refuseTable(entry, false)?.code).toBe('identity_tier');
      expect(refuseTable(entry, true)).toBeNull();
    }
  });
});
