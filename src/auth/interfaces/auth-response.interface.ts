/**
 * @fileoverview Response interfaces for authentication endpoints including sign-in, sign-up,
 * OTP verification, password reset, and profile retrieval. These types define the shapes
 * returned by {@link AuthService} methods.
 * @module src/auth/interfaces/auth-response.interface
 * @author Prince Jadiya
 */

import type { PublicUser } from '../../users/users.service';

/**
 * Minimal user information returned in authentication responses.
 */
export interface AuthUser {
  /** Application-level user ID from `public.users.id` */
  id: string;

  /** User's email address */
  email: string;

  /** User's first name, or null if not set */
  first_name: string | null;

  /** User's last name, or null if not set */
  last_name: string | null;
}

/**
 * JWT token pair returned after successful authentication or token refresh.
 */
export interface TokenResponse {
  /** Supabase JWT access token for authenticating API requests */
  access_token: string;

  /** Refresh token used to obtain a new access token when the current one expires */
  refresh_token: string;

  /** Number of seconds until the access token expires (typically 3600) */
  expires_in: number;

  /** Token type, always `"bearer"` */
  token_type: string;
}

/**
 * Extended token response that includes user profile data, returned on sign-in.
 */
export interface SigninResponse extends TokenResponse {
  /** The authenticated user's profile information */
  user: AuthUser;

  /** True when the password session must be upgraded with MFA before app entry */
  mfaRequired?: boolean;

  /** Current authenticator assurance level on the returned session */
  currentLevel?: string | null;

  /** Required authenticator assurance level for this user/session */
  nextLevel?: string | null;

  /** Server-derived primary method for the current authenticated session */
  authenticationMethod?: string | null;

  /** Safe reason code explaining why a step-up is required */
  stepUpReason?: string | null;

  /** True when a security-sensitive operation needs a fresh TOTP verification */
  recentTotpRequired?: boolean;

  /**
   * Fast-path landing organization resolved at sign-in.
   * `undefined` = the membership lookup failed (do not redirect to onboarding);
   * `null` = the user has zero memberships (redirect to onboarding);
   * an object = the organization to hard-navigate into.
   */
  defaultOrganization?: {
    id: string;
    slug: string;
    name: string;
    role: string;
  } | null;

  /** True when every organization the user belongs to is deactivated. */
  allOrganizationsDeactivated?: boolean;
}

/**
 * Result returned by the signup flow, containing the email and optional OTP for verification.
 */
export interface SignupResult {
  /** The email address used for registration */
  email: string;

  /** The OTP code generated for email verification, if applicable */
  otp?: string;
}

/**
 * Result returned when resending an OTP verification code.
 */
export interface OtpResult {
  /** The newly generated OTP code, or undefined if generation failed */
  otp?: string;

  /** True when Supabase Auth handled delivery through its own resend endpoint. */
  deliveredBySupabase?: boolean;
}

/**
 * Result returned by the forgot-password flow.
 */
export interface ForgotPasswordResult {
  /** The password reset link generated by Supabase, or undefined if the user was not found */
  resetLink?: string;

  /** The user's first name for personalized email greeting, if available */
  firstName?: string;
}

/**
 * Type alias for the user profile response, mapping directly to the {@link PublicUser} shape.
 */
export type ProfileResponse = PublicUser;
